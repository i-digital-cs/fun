/// Localized privacy policy copy (mirrors `lang/{en,ar}/privacy.php`).
class PrivacyPolicyCopy {
  const PrivacyPolicyCopy({
    required this.title,
    required this.updated,
    required this.intro,
    required this.contactEmail,
    required this.sections,
  });

  final String title;
  final String updated;
  final String intro;
  final String contactEmail;
  final List<PrivacyPolicySection> sections;

  static PrivacyPolicyCopy forLocale(String languageCode, {String brand = 'Funnity'}) {
    final isAr = languageCode.toLowerCase().startsWith('ar');
    final email = 'support@funnity.com';
    final raw = isAr ? _ar : _en;
    String fill(String text) => text
        .replaceAll(':brand', brand)
        .replaceAll(':email', email);

    return PrivacyPolicyCopy(
      title: raw.title,
      updated: fill(raw.updated),
      intro: fill(raw.intro),
      contactEmail: email,
      sections: [
        for (final section in raw.sections)
          PrivacyPolicySection(
            title: section.title,
            paragraphs: fill(section.body)
                .split(RegExp(r'\n\s*\n'))
                .map((p) => p.trim())
                .where((p) => p.isNotEmpty)
                .toList(),
          ),
      ],
    );
  }
}

class PrivacyPolicySection {
  const PrivacyPolicySection({required this.title, required this.paragraphs});

  final String title;
  final List<String> paragraphs;
}

